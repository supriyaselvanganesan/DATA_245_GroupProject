# confidence-based abstention analysis

def abstention_analysis(predictions_df):
    """
    Abstention means the model refuses to classify uncertain cases.

    For example:
    - p_pathogenic <= 0.20: predict benign
    - p_pathogenic >= 0.80: predict pathogenic
    - otherwise: abstain

    This does not change the official pred_label column.
    It is an additional uncertainty analysis.
    """

    confidence_ranges = [
        (0.00, 0.50),
        (0.10, 0.90),
        (0.20, 0.80),
        (0.30, 0.70),
        (0.40, 0.60)
    ]

    records = []

    for validation_name in predictions_df["validation"].unique():

        validation_data = predictions_df[
            predictions_df["validation"] == validation_name
        ].copy()

        for lower_probability, upper_probability in confidence_ranges:

            accepted = (
                (validation_data["p_pathogenic"] <= lower_probability)
                |
                (validation_data["p_pathogenic"] >= upper_probability)
            )

            accepted_data = validation_data[accepted].copy()

            if len(accepted_data) == 0:
                continue

            accepted_predictions = (
                accepted_data["p_pathogenic"] >= DEFAULT_THRESHOLD
            ).astype(int)

            accepted_accuracy = accuracy_score(
                accepted_data["label"],
                accepted_predictions
            )

            accepted_mcc = matthews_corrcoef(
                accepted_data["label"],
                accepted_predictions
            )

            coverage = len(accepted_data) / len(validation_data)

            records.append({
                "validation": validation_name,
                "lower_probability": lower_probability,
                "upper_probability": upper_probability,
                "accepted_cases": len(accepted_data),
                "abstained_cases": len(validation_data) - len(accepted_data),
                "coverage": coverage,
                "accuracy_on_accepted_cases": accepted_accuracy,
                "mcc_on_accepted_cases": accepted_mcc
            })

    return pd.DataFrame(records)


abstention_results = abstention_analysis(all_mkl_predictions)

print("Abstention analysis:")
display(abstention_results)

abstention_results.to_csv(
    "mkl_abstention_analysis.csv",
    index=False
)

