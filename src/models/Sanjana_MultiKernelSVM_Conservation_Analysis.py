RANDOM_STATE = 42

# Evaluation metrics

def calculate_metrics(y_true, probabilities, threshold=DEFAULT_THRESHOLD):
    """
    Calculate all required classification metrics.

    The official prediction label is created using threshold 0.50.
    A different threshold can be passed later for optional analysis.
    """

    y_true = np.asarray(y_true).astype(int)
    probabilities = np.asarray(probabilities)

    predictions = (probabilities >= threshold).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        predictions,
        labels=[0, 1]
    ).ravel()

    specificity = tn / (tn + fp) if (tn + fp) > 0 else np.nan

    metrics = {
        "accuracy": accuracy_score(y_true, predictions),
        "balanced_accuracy": balanced_accuracy_score(y_true, predictions),
        "precision": precision_score(
            y_true,
            predictions,
            zero_division=0
        ),
        "recall_sensitivity": recall_score(
            y_true,
            predictions,
            zero_division=0
        ),
        "specificity": specificity,
        "f1": f1_score(
            y_true,
            predictions,
            zero_division=0
        ),
        "mcc": matthews_corrcoef(y_true, predictions),
        "roc_auc": roc_auc_score(y_true, probabilities),
        "pr_auc": average_precision_score(y_true, probabilities),
        "true_negatives": tn,
        "false_positives": fp,
        "false_negatives": fn,
        "true_positives": tp
    }

    return metrics

# Use the shared outer folds

# This function does not create a train/test split.
# It reads the exact train/test assignments supplied by the team.

def get_outer_fold_ids(folds, validation_name, repeat_number, fold_number):
    """
    Return the training and testing VariationIDs for one exact
    shared assignment.

    The test set is the selected test_fold.
    The training set is the other four folds from the same
    validation mode and repeat.
    """

    same_repeat = folds[
        (folds["validation"] == validation_name)
        & (folds["repeat"] == repeat_number)
    ].copy()

    test_ids = same_repeat.loc[
        same_repeat["test_fold"] == fold_number,
        "VariationID"
    ].tolist()

    train_ids = same_repeat.loc[
        same_repeat["test_fold"] != fold_number,
        "VariationID"
    ].tolist()

    # Confirm that no variant appears in both sets.
    if set(train_ids).intersection(set(test_ids)):
        raise ValueError("Training and testing variants overlap.")

    return train_ids, test_ids

# Fit preprocessing and separate kernels

def fit_kernel_transformers(training_data):
    """
    Fit preprocessing only on the outer training data.

    This prevents information from the outer test fold leaking into:
    - missing-value imputation
    - scaling
    - kernel approximation
    """

    # Fit one imputer using only training values.
    imputer = SimpleImputer(strategy="median")

    X_train_raw = training_data[CONSERVATION_FEATURES].copy()
    X_train_imputed = imputer.fit_transform(X_train_raw)

    # Fit scaling only on training data.
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train_imputed)

    transformed_training_kernels = {}
    kernel_transformers = {}

    start_index = 0

    for group_name, group_features in CONSERVATION_GROUPS.items():

        number_of_features = len(group_features)
        end_index = start_index + number_of_features

        group_training_data = X_train_scaled[
            :, start_index:end_index
        ]

        # Each biological group receives its own RBF kernel approximation.
        # This is the central idea of the Multi-Kernel SVM.
        n_components_actual = min(
            N_COMPONENTS,
            group_training_data.shape[0]
        )

        nystroem = Nystroem(
            kernel="rbf",
            gamma=RBF_GAMMA,
            n_components=n_components_actual,
            random_state=RANDOM_STATE
        )

        transformed_group = nystroem.fit_transform(
            group_training_data
        )

        transformed_training_kernels[group_name] = transformed_group
        kernel_transformers[group_name] = nystroem

        start_index = end_index

    preprocessing_objects = {
        "imputer": imputer,
        "scaler": scaler,
        "kernel_transformers": kernel_transformers
    }

    return preprocessing_objects, transformed_training_kernels


def transform_data_using_training_objects(data_to_transform, preprocessing_objects):
    """
    Transform validation or testing data using objects already fitted
    on the training data.
    """

    imputer = preprocessing_objects["imputer"]
    scaler = preprocessing_objects["scaler"]
    kernel_transformers = preprocessing_objects["kernel_transformers"]

    X_raw = data_to_transform[CONSERVATION_FEATURES].copy()
    X_imputed = imputer.transform(X_raw)
    X_scaled = scaler.transform(X_imputed)

    transformed_kernels = {}

    start_index = 0

    for group_name, group_features in CONSERVATION_GROUPS.items():

        number_of_features = len(group_features)
        end_index = start_index + number_of_features

        group_data = X_scaled[
            :, start_index:end_index
        ]

        transformed_kernels[group_name] = (
            kernel_transformers[group_name]
            .transform(group_data)
        )

        start_index = end_index

    return transformed_kernels

# Combine the three kernel representations

def combine_kernel_features(transformed_kernels, weights):
    """
    Combine the three separate kernel representations.

    The square root of the weight is used so that the resulting
    feature-space inner product approximates:

        K = wp*Kp + wm*Km + wv*Kv

    This gives each biological evolutionary level its own contribution.
    """

    combined_parts = []

    for group_name in ["primate", "mammalian", "vertebrate"]:
        weight = weights[group_name]

        if weight > 0:
            weighted_features = (
                np.sqrt(weight)
                * transformed_kernels[group_name]
            )

            combined_parts.append(weighted_features)

    if len(combined_parts) == 0:
        raise ValueError("At least one kernel weight must be positive.")

    return np.hstack(combined_parts)

# Tune kernel weights and C using training data only

def get_inner_splits(
    y_training,
    groups_training,
    validation_name,
    random_state
):
    """
    Create inner folds only inside the current outer training set.

    These inner folds are not the final test folds.
    They are used only to choose:
    - the kernel combination
    - the SVM C value

    For gene-disjoint validation, GroupKFold prevents genes from
    appearing in both sides of an inner fold.
    """

    if validation_name == "standard":

        splitter = StratifiedKFold(
            n_splits=3,
            shuffle=True,
            random_state=random_state
        )

        return list(
            splitter.split(
                np.zeros(len(y_training)),
                y_training
            )
        )

    elif validation_name == "gene_disjoint":

        splitter = GroupKFold(n_splits=3)

        return list(
            splitter.split(
                np.zeros(len(y_training)),
                y_training,
                groups_training
            )
        )

    else:
        raise ValueError("Unknown validation mode.")


def tune_mkl_parameters(
    transformed_training_kernels,
    y_training,
    groups_training,
    validation_name,
    repeat_number,
    fold_number
):
    """
    Select the kernel weights and SVM C value using inner validation.

    The outer test fold is never used for tuning.
    PR-AUC is used as the tuning objective because the classes
    are not perfectly balanced.
    """

    inner_splits = get_inner_splits(
        y_training=y_training,
        groups_training=groups_training,
        validation_name=validation_name,
        random_state=RANDOM_STATE + repeat_number + fold_number
    )

    tuning_records = []

    best_score = -np.inf
    best_name = None
    best_weights = None
    best_C = None

    for weight_name, weights in KERNEL_WEIGHT_CANDIDATES.items():

        combined_training_features = combine_kernel_features(
            transformed_training_kernels,
            weights
        )

        for C_value in C_VALUES:

            inner_scores = []

            for inner_train_idx, inner_validation_idx in inner_splits:

                model = LinearSVC(
                    C=C_value,
                    class_weight="balanced",
                    max_iter=5000,
                    random_state=RANDOM_STATE
                )

                model.fit(
                    combined_training_features[inner_train_idx],
                    y_training[inner_train_idx]
                )

                validation_scores = model.decision_function(
                    combined_training_features[inner_validation_idx]
                )

                score = average_precision_score(
                    y_training[inner_validation_idx],
                    validation_scores
                )

                inner_scores.append(score)

            mean_inner_pr_auc = np.mean(inner_scores)

            tuning_records.append({
                "kernel_weight_name": weight_name,
                "primate_weight": weights["primate"],
                "mammalian_weight": weights["mammalian"],
                "vertebrate_weight": weights["vertebrate"],
                "C": C_value,
                "inner_pr_auc": mean_inner_pr_auc
            })

            if mean_inner_pr_auc > best_score:
                best_score = mean_inner_pr_auc
                best_name = weight_name
                best_weights = weights
                best_C = C_value

    tuning_table = pd.DataFrame(tuning_records)

    return (
        best_name,
        best_weights,
        best_C,
        best_score,
        tuning_table
    )

# Training-only probability calibration

def fit_calibrated_mkl_model(
    combined_training_features,
    y_training,
    groups_training,
    validation_name,
    C_value,
    repeat_number,
    fold_number
):
    """
    Fit the final SVM and a probability calibrator.

    LinearSVC produces decision scores, not probabilities.
    We use out-of-fold training scores to fit a logistic calibrator.

    The calibrator is trained only from the outer training set.
    The outer test set is not used during calibration.
    """

    inner_splits = get_inner_splits(
        y_training=y_training,
        groups_training=groups_training,
        validation_name=validation_name,
        random_state=RANDOM_STATE + 1000 + repeat_number + fold_number
    )

    out_of_fold_scores = np.zeros(len(y_training))

    for inner_train_idx, inner_validation_idx in inner_splits:

        inner_model = LinearSVC(
            C=C_value,
            class_weight="balanced",
            max_iter=5000,
            random_state=RANDOM_STATE
        )

        inner_model.fit(
            combined_training_features[inner_train_idx],
            y_training[inner_train_idx]
        )

        out_of_fold_scores[inner_validation_idx] = (
            inner_model.decision_function(
                combined_training_features[inner_validation_idx]
            )
        )

    # Convert decision scores into calibrated pathogenic probabilities.
    calibrator = LogisticRegression(
        max_iter=2000,
        class_weight=None
    )

    calibrator.fit(
        out_of_fold_scores.reshape(-1, 1),
        y_training
    )

    # Fit the final SVM on all outer training examples.
    final_model = LinearSVC(
        C=C_value,
        class_weight="balanced",
        max_iter=5000,
        random_state=RANDOM_STATE
    )

    final_model.fit(
        combined_training_features,
        y_training
    )

    return final_model, calibrator

# STANDARD VALIDATION

def run_mkl_evaluation(validation_name):
    """
    Run Multi-Kernel SVM evaluation using the exact shared folds.

    validation_name must be either:
    - standard
    - gene_disjoint
    """

    all_prediction_rows = []
    all_metric_rows = []
    all_tuning_rows = []

    # Use one unique copy of the modeling data.
    modeling_data = data.drop_duplicates(
        subset=[ID_COLUMN]
    ).set_index(ID_COLUMN)

    for repeat_number in sorted(folds["repeat"].unique()):

        for fold_number in sorted(folds["test_fold"].unique()):

            print(
                f"Running {validation_name} | "
                f"repeat={repeat_number} | fold={fold_number}"
            )

            train_ids, test_ids = get_outer_fold_ids(
                folds=folds,
                validation_name=validation_name,
                repeat_number=repeat_number,
                fold_number=fold_number
            )

            train_data = modeling_data.loc[train_ids].copy()
            test_data = modeling_data.loc[test_ids].copy()

            # Additional safety check for gene-disjoint validation.
            if validation_name == "gene_disjoint":

                training_genes = set(
                    train_data[GENE_COLUMN]
                )

                testing_genes = set(
                    test_data[GENE_COLUMN]
                )

                overlap = training_genes.intersection(testing_genes)

                if len(overlap) > 0:
                    raise ValueError(
                        "Gene overlap detected in gene-disjoint validation."
                    )

            y_train = train_data[TARGET_COLUMN].to_numpy()
            y_test = test_data[TARGET_COLUMN].to_numpy()

            groups_train = train_data[GENE_COLUMN].to_numpy()

            # Fit imputation, scaling, and kernels only on the outer training set.
            preprocessing_objects, transformed_train_kernels = (
                fit_kernel_transformers(train_data)
            )

            # Transform the outer test set using training-fitted objects.
            transformed_test_kernels = (
                transform_data_using_training_objects(
                    test_data,
                    preprocessing_objects
                )
            )

            # Tune using only the outer training set.
            (
                selected_weight_name,
                selected_weights,
                selected_C,
                best_inner_pr_auc,
                tuning_table
            ) = tune_mkl_parameters(
                transformed_training_kernels=transformed_train_kernels,
                y_training=y_train,
                groups_training=groups_train,
                validation_name=validation_name,
                repeat_number=repeat_number,
                fold_number=fold_number
            )

            # Store all inner tuning results for kernel analysis.
            tuning_table["validation"] = validation_name
            tuning_table["repeat"] = repeat_number
            tuning_table["fold"] = fold_number

            all_tuning_rows.append(tuning_table)

            # Combine kernels using the selected weights.
            combined_train = combine_kernel_features(
                transformed_train_kernels,
                selected_weights
            )

            combined_test = combine_kernel_features(
                transformed_test_kernels,
                selected_weights
            )

            # Fit the final SVM and training-only probability calibrator.
            final_model, calibrator = fit_calibrated_mkl_model(
                combined_training_features=combined_train,
                y_training=y_train,
                groups_training=groups_train,
                validation_name=validation_name,
                C_value=selected_C,
                repeat_number=repeat_number,
                fold_number=fold_number
            )

            # Get test decision scores.
            test_decision_scores = final_model.decision_function(
                combined_test
            )

            # Convert decision scores to calibrated probabilities.
            test_probabilities = calibrator.predict_proba(
                test_decision_scores.reshape(-1, 1)
            )[:, 1]

            # Required shared threshold.
            # This remains 0.50 for fair comparison with the other models.
            test_predictions = (
                test_probabilities >= DEFAULT_THRESHOLD
            ).astype(int)

            fold_metrics = calculate_metrics(
                y_true=y_test,
                probabilities=test_probabilities,
                threshold=DEFAULT_THRESHOLD
            )

            fold_metrics.update({
                "model": "Multi-Kernel SVM",
                "feature_set": FEATURE_SET_NAME,
                "validation": validation_name,
                "repeat": repeat_number,
                "fold": fold_number,
                "selected_kernel_weights": selected_weight_name,
                "primate_weight": selected_weights["primate"],
                "mammalian_weight": selected_weights["mammalian"],
                "vertebrate_weight": selected_weights["vertebrate"],
                "selected_C": selected_C,
                "best_inner_pr_auc": best_inner_pr_auc,
                "threshold": DEFAULT_THRESHOLD
            })

            all_metric_rows.append(fold_metrics)

            # Save predictions using the team's shared required format.
            for variant_id, true_label, probability, prediction in zip(
                test_data.index,
                y_test,
                test_probabilities,
                test_predictions
            ):

                all_prediction_rows.append({
                    "model": "Multi-Kernel SVM",
                    "feature_set": FEATURE_SET_NAME,
                    "validation": validation_name,
                    "repeat": repeat_number,
                    "fold": fold_number,
                    "VariationID": variant_id,
                    "label": int(true_label),
                    "p_pathogenic": float(probability),
                    "pred_label": int(prediction)
                })

    predictions_df = pd.DataFrame(all_prediction_rows)
    metrics_df = pd.DataFrame(all_metric_rows)
    tuning_df = pd.concat(
        all_tuning_rows,
        ignore_index=True
    )

    return predictions_df, metrics_df, tuning_df

